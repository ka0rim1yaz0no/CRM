import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { runInNewContext } from "node:vm";
import ts from "typescript";
import { PDFDocument, PageSizes } from "pdf-lib";
const require = createRequire(import.meta.url);
const source = readFileSync(new URL("../src/lib/payslipPdf.ts", import.meta.url), "utf8");
function moduleWith(overrides = {}) {
    const exports = {};
    runInNewContext(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText,
        { exports, require, Uint8Array, ArrayBuffer, setTimeout, clearTimeout, setInterval, clearInterval, ...overrides });
    return exports;
}
const pdf = moduleWith();
test("one-page PDF placement preserves the complete image inside A4 and Letter margins", () => {
    for (const [width, height] of [PageSizes.A4, PageSizes.Letter]) for (const [iw, ih] of [[2157, 2655], [100, 10000], [10000, 100]]) {
        const p = pdf.fitPayslipOnPage(iw, ih, width, height), margin = 10 * 72 / 25.4;
        assert.ok(p.x >= margin - 0.001 && p.y >= margin - 0.001);
        assert.ok(p.x + p.width <= width - margin + 0.001 && p.y + p.height <= height - margin + 0.001);
        assert.ok(Math.abs(p.width / p.height - iw / ih) < 0.00001);
    }
    assert.throws(() => pdf.fitPayslipOnPage(0, 10, 100, 100));
});
test("generated bytes are a readable single-page PDF with the correct paper size and title", async () => {
    const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jMNsAAAAASUVORK5CYII=";
    for (const paper of ["A4", "Letter"]) {
        const bytes = await pdf.buildPayslipPdf(png, "Synthetic Payslip", paper);
        const reopened = await PDFDocument.load(bytes);
        assert.equal(reopened.getPageCount(), 1); assert.equal(reopened.getTitle(), "Synthetic Payslip");
        assert.deepEqual([reopened.getPage(0).getWidth(), reopened.getPage(0).getHeight()], PageSizes[paper]);
    }
});
test("PDF preparation rejects stalled work and clears its deadline after success", async () => {
    await assert.rejects(pdf.withPdfDeadline(new Promise(() => {}), 10), /timed out/);
    assert.equal(await pdf.withPdfDeadline(Promise.resolve("done"), 1000), "done");
});
test("PDF snapshot is removed after capture errors and never edits the displayed payslip", async () => {
    let removed = 0, appended = 0, cloned = 0;
    const snapshot = { style: {}, removeAttribute() {}, querySelector: () => null, remove() { removed++; } };
    const sheet = { cloneNode() { cloned++; return snapshot; } };
    const browserPdf = moduleWith({ document: { body: { append() { appended++; } }, fonts: { ready: Promise.resolve() } } });
    await assert.rejects(browserPdf.capturePayslipPdf(sheet, "Synthetic"), /unavailable/);
    assert.equal(cloned, 1); assert.equal(appended, 1); assert.equal(removed, 1);
});
